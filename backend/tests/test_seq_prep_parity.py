"""Parity between the Python construct builder and the TypeScript it replaced.

The vectors in ``fixtures/seq_prep_vectors.json`` are generated by running the
original TS (see ``fixtures/regenerate_seq_prep_vectors.sh``). They cover the two
ports whose behaviour is hardest to verify by inspection: the isoelectric-point
bisection, and short-name generation.
"""

import json
import math
from pathlib import Path

import pytest

from backend.seq_prep.protparam import (
    isoelectric_point,
    molar_extinction_coefficient,
    sequence_warnings,
)
from backend.seq_prep.shortnames import (
    ShortNameRowInput,
    ShortNameStrategy,
    compute_short_names,
    hash_base52,
    sanitize_short_name_segment,
)

VECTORS = json.loads(
    (Path(__file__).parent / "fixtures" / "seq_prep_vectors.json").read_text()
)

# The TS rows the vectors were generated from.
ROWS = [
    ShortNameRowInput("k1", "batch-1_designA_model0", "MKWVTFISLL", "MKWVTFISLL*", "ATGAAATGGGTTACCTTCATTTCTCTGCTGTAA", "N"),
    ShortNameRowInput("k2", "batch-1_designB_model0", "GGCDEFHIKW", "GGCDEFHIKW*", "GGTGGTTGCGATGAATTCCATATTAAATGGTAA", "C"),
    ShortNameRowInput("k3", "batch-2_designC_model1", "MMMMMMKKKK", "MMMMMMKKKK*", "ATGATGATGATGATGATGAAAAAAAAAAAATAA", "N"),
    ShortNameRowInput("k4", "batch-2_designC_model1", "MMMMMMKKKK", "MMMMMMKKKK*", "ATGATGATGATGATGATGAAAAAAAAAAAATAA", "N"),
]

_SPEC_KEY_MAP = {
    "pattern": "pattern", "replacement": "replacement", "flags": "flags",
    "delimiter": "delimiter", "indices": "indices", "addPrefix": "add_prefix",
    "addSuffix": "add_suffix", "addHash": "add_hash", "prefix": "prefix",
    "uidLength": "uid_length", "numberPad": "number_pad", "includeHash": "include_hash",
    "includeIndex": "include_index", "removeCommonPrefix": "remove_common_prefix",
    "removeCommonSuffix": "remove_common_suffix", "prefixPattern": "prefix_pattern",
    "suffixPattern": "suffix_pattern", "newPrefix": "new_prefix", "hashLen": "hash_len",
}


def _strategy_from_spec(spec: dict) -> ShortNameStrategy:
    kwargs = {_SPEC_KEY_MAP[k]: v for k, v in spec.items() if k in _SPEC_KEY_MAP}
    return ShortNameStrategy(kind=spec["kind"], **kwargs)


@pytest.mark.parametrize("case", VECTORS["protparam"], ids=lambda c: c["sequence"][:20] or "empty")
def test_protparam_matches_typescript(case):
    reduced, oxidized = molar_extinction_coefficient(case["sequence"])
    assert reduced == case["extinction_reduced"]
    assert oxidized == case["extinction_oxidized"]
    assert sequence_warnings(case["sequence"]) == case["warnings"]

    pi = isoelectric_point(case["sequence"])
    if case["isoelectric_point"] is None:
        assert math.isnan(pi)
    else:
        # Both sides bisect to a 1e-4 tolerance, so agreement below that is all
        # the algorithm promises; exports round well above it.
        assert pi == pytest.approx(case["isoelectric_point"], abs=1e-9)


@pytest.mark.parametrize("case", VECTORS["hash_base52"], ids=lambda c: c["input"][:20] or "empty")
def test_fnv_hash_matches_typescript(case):
    assert hash_base52(case["input"], 5) == case["len5"]
    assert hash_base52(case["input"], 10) == case["len10"]


@pytest.mark.parametrize("case", VECTORS["sanitize"], ids=lambda c: repr(c["input"]))
def test_sanitize_matches_typescript(case):
    assert sanitize_short_name_segment(case["input"]) == case["output"]


@pytest.mark.parametrize("case", VECTORS["short_names"], ids=lambda c: c["strategy"])
def test_short_names_match_typescript(case):
    result = compute_short_names(ROWS, _strategy_from_spec(case["spec"]), 32)
    assert [[k, result.names[k]] for k, _ in case["names"]] == case["names"]
    assert result.dedupe_count == case["dedupe_count"]
    assert sorted(result.non_unique_row_keys) == case["non_unique"]
